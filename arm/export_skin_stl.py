"""Export the frozen v10.6 skin as print STLs + a parts list: arm/skin-stl/.

Each part in its own link frame, mm. Sleeves (upper, upperd, forearm, wrist, turret) split front / back at
the arm's y = 0 plane (their parting line). The upper sleeve carries J3's dot-grid fields and is
handed: L (front = arm -y clean) and R (front = arm +y clean). Desk-only parts (base puck, J1 drum) and
the body-only J1 face ring are exported from their own builds.

The meshes are the skin's OUTER surfaces as solids. Shell them to the wall in CAD / the slicer: 0.9 mm
(sleeves, J4 / J6 rings, MJF PA12 with ribs), 1.2 mm (everything else), the inner face open. Volumes
below are wall x outer area, i.e. the printed material, not the solid.

    uv run -q --with numpy --with manifold3d --with trimesh --with scipy python arm/export_skin_stl.py
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'skin-stl')

CHILD = r'''
import os, sys, json
sys.path.insert(0, %r)
import numpy as np, trimesh
from manifold3d import Manifold
import skin_v10 as S
out, tag, only = %r, %r, %r
rows = []
for nm, link, m, mat in S.skin_meshes():
    if only and not nm.startswith(tuple(only)):
        continue
    if nm.startswith('cap-'):
        nm_ = nm
    else:
        nm_ = nm
    halves = nm in ('upper', 'upperd', 'fore', 'wrist', 'turret')
    pieces = []
    if halves:
        M = Manifold(S._mm(m))
        for side, sg in (('front', -1), ('back', 1)):
            box = trimesh.creation.box(extents=[2000.0, 1000.0, 2000.0]).apply_translation([0, sg * 500.0, 0])
            pieces.append(('%%s-%%s' %% (nm, side), S._tm(M ^ Manifold(S._mm(box)))))
    else:
        pieces.append((nm, m))
    for pn, pm in pieces:
        fn = '%%s%%s.stl' %% (pn, tag)
        pm.export(os.path.join(out, fn))
        wall = S.WALL_THIN.get(nm, S.WALL)
        if nm.startswith('puck'):
            R_, W_ = pm.extents[0] / 2, pm.extents[1]
            area = (2 * 3.14159 * R_ * W_ + 2 * 3.14159 * (R_ ** 2 - (R_ - 7.0) ** 2)) * 1e-6
        elif nm.startswith('ring-'):
            area = 4 * (pm.area * 0.5) ** 0.5 * min(pm.extents) * 1e-6
        else:
            area = (pm.convex_hull.area if halves else pm.area * 0.5) * 1e-6
        rows.append(dict(file=fn, part=pn + tag, link=link, finish=mat, wall_mm=wall * 1e3,
                         volume_cm3=round(area * wall * 1e6, 1), bbox_mm=[round(v) for v in pm.extents]))
print(json.dumps(rows))
'''


def run(env, tag, only=()):
    src = CHILD % (HERE, OUT, tag, list(only))
    r = subprocess.run([sys.executable, '-c', src], env=dict(os.environ, ROSE_ARM='v10', LYMB_PUCK_HOLES='0', **env), capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr[-2000:])
    return json.loads(r.stdout.strip().splitlines()[-1])


def main():
    os.makedirs(OUT, exist_ok=True)
    desk = run({'ROSE_ARM_SIDE': 'l'}, '')
    right = run({'ROSE_ARM_SIDE': 'r'}, '_R', ('upper',))
    right = [r for r in right if r['part'].startswith('upper-')]
    body = run({'ROSE_ARM_PEDESTAL': '0', 'ROSE_ARM_PED_H': '0.04105'}, '_body', ('flank-J1', 'turret'))
    for r in desk:
        if r['part'].startswith('upper-'):
            r['part'] += ' (L)'
    proc = {'skin': 'MJF PA12, dyed warm black, vapour-smoothed satin', 'puck': 'MJF PA12, dyed graphite (or turned 6061, hard-anodized)',
            'trim': 'turned 6061, gunmetal anodize (or SLA + PVD)', 'accent': 'SLA, Make green #39ff14', 'vent': 'MJF PA12'}
    rows = desk + right + body
    L = ['# lymb v10.6 skin: print parts (frozen)', '',
         'Generated by `export_skin_stl.py`. STLs are the outer surfaces as solids, in each part\'s link frame (mm);',
         'shell them to the listed wall with the inner face open. Volume = printed material (wall x outer area).',
         'Desk build: everything except `*_body`. Humanoid build: per arm, `*_body` replaces `desk-puck`, `drum-J1` and',
         'the desk `turret-*` halves; use `upper-*` on the left arm and `upper-*_R` on the right.', '',
         '| file | part | link | finish | process | wall mm | qty / arm | volume cm³ | bbox mm |', '|---|---|---|---|---|---:|---:|---:|---|']
    for r in rows:
        qty = 1
        L.append('| %s | %s | %s | %s | %s | %.1f | %d | %.1f | %s |' % (r['file'], r['part'], r['link'], r['finish'], proc.get(r['finish'], ''),
                                                                    r['wall_mm'], qty, r['volume_cm3'], ' x '.join(str(v) for v in r['bbox_mm'])))
    tot = sum(r['volume_cm3'] for r in desk)
    L += ['', 'Desk arm: %d parts, %.0f cm³ of material.' % (len(desk), tot),
          'Fastening (clips, magnets, standoffs, VHB) is in V10.4.md; it needs no new plate holes.', '',
          '**Ring pucks\' dot-grid (not meshed in these STLs, to keep them printable / small):** Ø1.3 radial holes on a 2.3 mm',
          'hex round the full circumference of puck-J2 / J4 / J6, rows from 4 mm inside each face to 4 mm inside the other;',
          'circumferential pitch 2.3 mm on the ring\'s OD, alternate rows offset half a pitch (29 % open). Add it in CAD.',
          'The J3 (upper-*) and J7 (wrist-*) dot-grid fields ARE in the STLs (Ø1.4 / 2.2 hex on the upper sleeve, Ø1.3 / 2.3 on the wrist).']
    open(os.path.join(OUT, 'PARTS.md'), 'w').write('\n'.join(L) + '\n')
    print('%d STLs in %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
