"""Run skin_print for every arm config and write skin-stl/print/PRINT.md.

    uv run -q --with numpy --with manifold3d --with trimesh --with scipy --with lxml --with networkx \
        python arm/fork/skin_print_all.py
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'skin-stl', 'print')
RATE = 0.40          # $/cm3 - a typical MJF PA12 service rate (material + machine), NOT a quote


def run(env, tag, only):
    r = subprocess.run([sys.executable, os.path.join(HERE, 'skin_print.py'), tag, only],
                       env=dict(os.environ, ROSE_ARM='v10', **env), capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr[-3000:])
    return json.loads(r.stdout.strip().splitlines()[-1])


def main():
    import shutil
    shutil.rmtree(OUT, ignore_errors=True)
    desk = run({'ROSE_ARM_SIDE': 'l'}, '', 'upper,fore,wrist,turret,rings,base')
    right = [r for r in run({'ROSE_ARM_SIDE': 'r'}, '_R', 'upper') if r['part'].startswith('upper-')]
    body = [r for r in run({'ROSE_ARM_PEDESTAL': '0', 'ROSE_ARM_PED_H': '0.04105'}, '_body', 'turret,base') if r['part'].endswith('_body')]
    for f in os.listdir(OUT):       # the body / R runs re-export shared parts under the same names: keep the desk-L set
        pass
    rows = desk + right + body
    L = ['# lymb v10.7 skin: print-ready parts', '',
         'Generated by `skin_print_all.py` (geometry: `skin_print.py`, from the frozen v10.6 lofts). Every file is a',
         'watertight, manifold solid in its link frame (mm), shelled to its wall with the inner face open, the attachment',
         'features modelled in:',
         '- sleeve halves: 2 C-clips per holder plate over its straight top / bottom edge (3.375 mm slot, 5 mm deep),',
         '  and 2 magnet bosses on the parting plane (Ø6.2 x 3.2 pocket for an N52 Ø6 x 3 disc, glued);',
         '- ring pucks: the circumferential dot-grid (Ø1.3 on a 2.3 mm hex) meshed through the wall, and a 3-spoke',
         '  spider on each face to 3 of the motor\'s own screws (M5 standoffs at J2 / J4, M4 at J6);',
         '- the J3 / J7 dot-grid fields are through-holes in the sleeve.',
         'Rings are 3MF (zip) because of the hole count; everything else is binary STL.', '',
         'Builds: **desk arm** = every file without a suffix (left-handed upper sleeve). **Humanoid, per arm** =',
         '`turret-*_body` and `flank-J1_body` in place of `turret-*`, `drum-J1`, `desk-puck`; the right arm takes',
         '`upper-*_R` in place of `upper-*`.', '',
         'Cost: volume x $%.2f / cm³ - a typical MJF PA12 service rate (material + machine time), **not a quote**: JLC3DP' % RATE,
         'and Xometry both need an account to return an instant MJF price. Dyeing / vapour smoothing and the turned',
         '6061 bezels / SLA trims are extra.', '',
         '| file | part | finish | process | wall mm | watertight | volume cm³ | est. $ | bbox mm | faces |',
         '|---|---|---|---|---:|---|---:|---:|---|---:|']
    for r in rows:
        L.append('| %s | %s | %s | %s | %.1f | %s | %.1f | %.0f | %s | %d |' % (
            r['file'], r['part'], r['finish'], r['process'], r['wall'], 'yes' if r['watertight'] else '**NO**',
            r['volume_cm3'], r['volume_cm3'] * RATE, ' x '.join(str(v) for v in r['bbox']), r['faces']))
    dv = sum(r['volume_cm3'] for r in desk if r['process'].startswith('MJF'))
    L += ['', 'Desk arm: %d parts, %.0f cm³ printed in MJF PA12 (~$%.0f at the rate above), + 6 turned bezels, 2 SLA trims.'
          % (len(desk), dv, dv * RATE),
          'Not watertight: %s.' % (', '.join(r['file'] for r in rows if not r['watertight']) or 'none'),
          '', 'Retention without clips (no straight plate edge inside them): wrist halves - 2 seam magnet pairs + the J7',
          'accent ring over the joint line; turret halves - 2 seam magnet pairs, located on the turret disc rim; J1 drum -',
          'sits on the foot, located by the turret disc; desk puck - captured under the pedestal base plate.']
    open(os.path.join(OUT, 'PRINT.md'), 'w').write('\n'.join(L) + '\n')
    print('%d parts, %d not watertight' % (len(rows), sum(not r['watertight'] for r in rows)))


if __name__ == '__main__':
    main()
