def lmr(part_name, vin, vout, fb_top, fb_bot, lval, en, pg):
    p = kicad_pins('Regulator_Switching', part_name)
    rr = ref('U')
    pins = []
    for name, nums in p.items():
        known = {'VIN': vin, 'EN': en, 'PGND': 'GND', 'AGND': 'GND', 'GND': 'GND', 'SW': f'{rr}_SW', 'BOOT': f'{rr}_BOOT',
                 'VCC': f'{rr}_VCC', 'FB': f'{rr}_FB', 'PG': pg, 'EP': 'GND', 'PAD': 'GND'}
        assert name in known, (part_name, name)
        net = known[name]
        pins += [(n, net) for n in nums]
    part(rr, f'Regulator_Switching:{part_name}', part_name, 'Package_SO:Texas_HSOP-8-1EP_3.9x4.9mm_P1.27mm_ThermalVias', pins)
    c('100n', f'{rr}_BOOT', f'{rr}_SW')
    c('1u', f'{rr}_VCC')
    decouple(vin, '2x10u 25V', '100n')
    l(lval, f'{rr}_SW', vout, 'Inductor_SMD:L_Bourns_SRN6045TA')
    r(fb_top, vout, f'{rr}_FB')
    r(fb_bot, f'{rr}_FB', 'GND')
    decouple(vout, '3x22u', '100n')
    return rr


