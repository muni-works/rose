def soc_ball(tok):
    """The one ball whose datasheet name has `tok` as a whole function ('GPIO1_B3', 'XIN_24M')."""
    m = [b for b, n in SOC if re.search(r'(^|/)\s*' + re.escape(tok) + r'(_[a-z])?(/|$)', n)]
    assert len(m) == 1, (tok, m)
    return m[0]


def soc(tok, net):
    b = soc_ball(tok)
    assert b not in soc_net, (tok, b, soc_net[b])
    soc_net[b] = net
    return b


