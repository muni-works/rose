def kicad_pins(lib, sym):
    """name -> [numbers] for a KiCad library symbol (follows `extends`)."""
    t = open(os.path.join(KICAD_SYM, lib + '.kicad_sym')).read()
    i = t.index(f'(symbol "{sym}"')
    j = t.find('\n\t(symbol "', i + 10)
    blk = t[i:j if j > 0 else len(t)]
    m = re.search(r'\(extends "([^"]+)"\)', blk)
    if m:
        return kicad_pins(lib, m.group(1))
    pins = defaultdict(list)
    for name, num in re.findall(r'\(pin \w+ \w+.*?\(name "([^"]*)".*?\(number "([^"]*)"', blk, re.S):
        pins[name].append(num)
    return pins


