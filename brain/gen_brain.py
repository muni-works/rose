def q(s):
    return '"' + s.replace('"', '\\"') + '"'


def part(r, lib, val, fp, pins):
    """pins: [(pin_number, net)]; a None net leaves the pin unconnected."""
    flat = ' '.join(f'{q(p)} {q(n)}' for p, n in pins if n)
    emit(f'[part {q(r)} {q(lib)} {q(val)} {q(fp)}\n  #[{flat}]]')
    return r


