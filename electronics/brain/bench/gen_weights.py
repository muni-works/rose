"""Random int8 weights in the S0 actor's shape, as a C header for s0_int8.c.

    python3 gen_weights.py > s0_weights.h

Timing doesn't depend on the values. Rows are padded to a multiple of 4 bytes
(the SMLAD loop reads 4 at a time).
"""
import random

N = [710, 512, 256, 128, 20]
random.seed(7)
print('/* generated by gen_weights.py - do not edit */')
print('#include <stdint.h>')
for k, n in enumerate(N):
    print(f'#define S0_N{k} {n}')
scales = []
for k in range(4):
    n_in, n_out = N[k], N[k + 1]
    stride = (n_in + 3) & ~3
    w = []
    for _ in range(n_out):
        w += [random.randint(-127, 127) for _ in range(n_in)] + [0] * (stride - n_in)
    print(f'__attribute__((aligned(4))) const int8_t s0_w{k}[{len(w)}] = {{')
    for i in range(0, len(w), 32):
        print(','.join(map(str, w[i:i + 32])) + ',')
    print('};')
    b = [random.uniform(-0.1, 0.1) for _ in range(n_out)]
    print(f'const float s0_b{k}[{n_out}] = {{' + ','.join(f'{v:.5f}f' for v in b) + '};')
    scales.append((1.0 / n_in ** 0.5) / 127.0)
print('const float s0_scale[4] = {' + ','.join(f'{s:.8e}f' for s in scales) + '};')
