"""Emit rose-pro as a vcad loon program.

The plate table in rose_pro_links.py stays the single source of truth (it carries the
clearance, edge-margin and bend-rule checks); this writes it out as loon so vcad does
the actual geometry. Nothing here generates geometry - it generates vcad source.

vcad conventions that shape the output:
  * Z-up, mm, degrees. cube corner at origin; cylinder axis +Z, base at z=0.
  * subject-last, so [difference tool subject] and [pipe base [difference tool] ...].
  * loon hardcodes 32 tessellation segments; nothing here depends on chord accuracy.
  * bores are kept exiting PLANAR faces. Per vcad's boolean-fidelity matrix the
    degrading cells are through-cuts breaking out of ROUND walls, which would cost
    the analytic B-rep and hand us faceted STEP. Plate faces are flat, so we stay in
    the well-conditioned corner of that matrix.
"""
import os
import sys
import json

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rose_pro_links as L

AXI = {'x': 0, 'y': 1, 'z': 2}
OUT = os.path.expanduser('~/Developer/vcad/hardware/rose-pro/rose-pro.loon')

HEADER = '''; rose-pro - original 22-DOF humanoid, structure in 3 mm 5052 sheet.
;
; Not a K1 clone. The K1's joint axes are too tightly packed for off-the-shelf
; actuators - its hip roll and yaw axes intersect at a point - so this is an
; original layout designed around MyActuator X-series envelopes, verified against
; the vendor installation drawings:
;
;   X6-60  D80.0 x 67.5, stator 12xM3 on D72.5, output 12xM4 on D44, D53 spigot
;   X4-36  D55.0 x 61.0, stator  6xM3 on D48,   output  6xM3 on D26, D35 boss
;   X4-10  D55.0 x 55.5, same pattern as X4-36
;
; Structure is cut-and-bent sheet: laser blanks + press brake + bolts. Couplings
; are one blank where the bend line clears both bolt circles, two bends with a
; corner relief where it crosses one, and two lapped pieces where it lands inside
; a circle (hip roll, ankle, shoulder). See pro/rose_pro_bent.py for the
; per-coupling determination.
;
; Robot 17.58 kg, 1130 mm, stance 150 mm, thigh:shank 1:1. Loads in phyz and
; stands at +0.0% ground-force error.
;
; Generated by pro/rose_pro_loon.py in the rose repo - edit the table there.

'''

HELPERS = '''
; ---------------------------------------------------------------- helpers ----
; Rounded-rectangle plate, one per normal axis. u/v are the two in-plane axes in
; x<y<z order, n0..n1 the thickness span. Corner radius r.
; Built as two overlapping boxes plus four corner cylinders - the classic
; rounded-rect, and every resulting face is planar or a simple cylinder.

[let plate-x [fn [n0 n1 u0 u1 v0 v1 r]
  [let t [- n1 n0]]
  [let core [translate n0 [+ u0 r] v0 [cube t [- [- u1 u0] [* 2.0 r]] [- v1 v0]]]]
  [let cross [translate n0 u0 [+ v0 r] [cube t [- u1 u0] [- [- v1 v0] [* 2.0 r]]]]]
  [let cn [fn [cu cv] [translate n0 cu cv [rotate 0.0 90.0 0.0 [cylinder r t]]]]]
  [pipe core [union cross]
        [union [cn [+ u0 r] [+ v0 r]]] [union [cn [+ u0 r] [- v1 r]]]
        [union [cn [- u1 r] [+ v0 r]]] [union [cn [- u1 r] [- v1 r]]]]]]

[let plate-y [fn [n0 n1 u0 u1 v0 v1 r]
  [let t [- n1 n0]]
  [let core [translate [+ u0 r] n0 v0 [cube [- [- u1 u0] [* 2.0 r]] t [- v1 v0]]]]
  [let cross [translate u0 n0 [+ v0 r] [cube [- u1 u0] t [- [- v1 v0] [* 2.0 r]]]]]
  [let cn [fn [cu cv] [translate cu n0 cv [rotate -90.0 0.0 0.0 [cylinder r t]]]]]
  [pipe core [union cross]
        [union [cn [+ u0 r] [+ v0 r]]] [union [cn [+ u0 r] [- v1 r]]]
        [union [cn [- u1 r] [+ v0 r]]] [union [cn [- u1 r] [- v1 r]]]]]]

[let plate-z [fn [n0 n1 u0 u1 v0 v1 r]
  [let t [- n1 n0]]
  [let core [translate [+ u0 r] v0 n0 [cube [- [- u1 u0] [* 2.0 r]] [- v1 v0] t]]]
  [let cross [translate u0 [+ v0 r] n0 [cube [- u1 u0] [- [- v1 v0] [* 2.0 r]] t]]]
  [let cn [fn [cu cv] [translate cu cv n0 [cylinder r t]]]]
  [pipe core [union cross]
        [union [cn [+ u0 r] [+ v0 r]]] [union [cn [+ u0 r] [- v1 r]]]
        [union [cn [- u1 r] [+ v0 r]]] [union [cn [- u1 r] [- v1 r]]]]]]

; Through-bores, overshooting the plate both ways so the cut exits cleanly.
[let bore-x [fn [d cu cv n0 n1]
  [translate [- n0 2.0] cu cv [rotate 0.0 90.0 0.0 [cylinder [/ d 2.0] [+ [- n1 n0] 4.0]]]]]]
[let bore-y [fn [d cu cv n0 n1]
  [translate cu [- n0 2.0] cv [rotate -90.0 0.0 0.0 [cylinder [/ d 2.0] [+ [- n1 n0] 4.0]]]]]]
[let bore-z [fn [d cu cv n0 n1]
  [translate cu cv [- n0 2.0] [cylinder [/ d 2.0] [+ [- n1 n0] 4.0]]]]]

; Actuator envelope stand-ins - purchased parts, shown for fit not for manufacture.
[let act-x [fn [d lo hi cu cv] [translate lo cu cv [rotate 0.0 90.0 0.0 [cylinder [/ d 2.0] [- hi lo]]]]]]
[let act-y [fn [d lo hi cu cv] [translate cu lo cv [rotate -90.0 0.0 0.0 [cylinder [/ d 2.0] [- hi lo]]]]]]
[let act-z [fn [d lo hi cu cv] [translate cu cv lo [cylinder [/ d 2.0] [- hi lo]]]]]
'''


def fnum(v):
    return '%.4f' % v


def plate_expr(pl, mirror):
    nm = pl['normal']
    i = AXI[nm]
    ui, vi = [k for k in range(3) if k != i]
    n0, n1 = pl['n0'], pl['n1']
    u0, u1, v0, v1 = pl['u0'], pl['u1'], pl['v0'], pl['v1']
    holes = [tuple(h) for h in pl['holes']]
    if mirror:
        if i == 1:
            n0, n1 = -n1, -n0
        elif ui == 1:
            u0, u1 = -u1, -u0
            holes = [(-h[0], h[1], h[2]) for h in holes]
        elif vi == 1:
            v0, v1 = -v1, -v0
            holes = [(h[0], -h[1], h[2]) for h in holes]
    r = min(8.0, (u1 - u0) / 2.5, (v1 - v0) / 2.5)
    base = '[plate-%s %s %s %s %s %s %s %s]' % (
        nm, fnum(n0), fnum(n1), fnum(u0), fnum(u1), fnum(v0), fnum(v1), fnum(r))
    # ONE difference against a unioned tool, not a chain of them. Chaining costs
    # ~27 s for a 13-hole plate because every cut re-processes the whole accumulated
    # mesh; the holes are disjoint, so unioning them first is nearly free.
    cuts = []
    for (hu, hv, hd) in holes:
        if not (u0 < hu < u1 and v0 < hv < v1):
            continue
        cuts.append('[bore-%s %s %s %s %s %s]'
                    % (nm, fnum(hd), fnum(hu), fnum(hv), fnum(n0), fnum(n1)))
    if not cuts:
        return base
    tool = cuts[0]
    for c in cuts[1:]:
        tool = '[union %s %s]' % (c, tool)
    return '[difference %s\n    %s]' % (tool, base)


def actuator_exprs():
    out = []
    for name, j in L.JOINTS.items():
        lo, hi, _ = L.body_span(j)
        i = AXI[j['ax']]
        ui, vi = [k for k in range(3) if k != i]
        d = L.IFACE[j['m']]['od']
        for side, sgn in ((('L', 1), ('R', -1)) if j['c'][1] != 0 else (('C', 1),)):
            cu, cv = j['c'][ui], j['c'][vi]
            a_lo, a_hi = lo, hi
            if sgn < 0:
                if i == 1:
                    a_lo, a_hi = -hi, -lo
                elif ui == 1:
                    cu = -cu
                elif vi == 1:
                    cv = -cv
            out.append(('%s_%s' % (side, name),
                        '[act-%s %s %s %s %s %s]' % (j['ax'], fnum(d), fnum(a_lo),
                                                     fnum(a_hi), fnum(cu), fnum(cv))))
    return out


def main():
    data = L.dump_json(os.path.expanduser('~/Developer/pond_assets/rose_pro_plates.json'))
    groups = {}
    for pl in data['plates']:
        groups.setdefault(pl['link'], []).append(pl)

    lines = [HEADER]
    lines.append('[defparam hip_y      %s :unit "mm"]' % fnum(L.HIP_Y))
    lines.append('[defparam shoulder_y %s :unit "mm"]' % fnum(L.SHO_Y))
    lines.append('[defparam sheet_t    %s :unit "mm"]' % fnum(L.T))
    lines.append('[defparam bend_r     1.5 :unit "mm"]')
    lines.append(HELPERS)

    no_mirror = ('neck', 'trunkC', 'head')
    roots = []
    lines.append('\n; ----------------------------------------------------- structure ----')
    for link in sorted(groups):
        sides = [(False, 'C')] if link in no_mirror else [(False, 'L'), (True, 'R')]
        for mirror, tag in sides:
            name = '%s_%s' % (tag, link)
            exprs = [plate_expr(pl, mirror) for pl in groups[link]]
            body = exprs[0]
            for e in exprs[1:]:
                body = '[union %s\n  %s]' % (e, body)
            lines.append('\n[let %s\n  %s]' % (name, body))
            roots.append((name, 'aluminum'))

    lines.append('\n; ------------------------------------------- actuator envelopes ----')
    for name, expr in actuator_exprs():
        lines.append('[let act_%s %s]' % (name, expr))
        roots.append(('act_%s' % name, 'actuator'))

    lines.append('\n[material "actuator" 0.10 0.10 0.11 0.6 0.5]')
    lines.append('\n; ---------------------------------------------------------- roots ----')
    for name, mat in roots:
        lines.append('[root %s "%s"]' % (name, mat))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    nplate = sum(len(v) for v in groups.values())
    print('wrote %s' % OUT)
    print('  %d plate definitions -> %d solids, %d actuator envelopes, %d roots'
          % (nplate, sum(1 for r in roots if not r[0].startswith('act_')),
             sum(1 for r in roots if r[0].startswith('act_')), len(roots)))


if __name__ == '__main__':
    main()
